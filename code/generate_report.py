"""
Reads everything run_experiments.py wrote to Result/ and writes a short,
human-readable Result/README.md summarising what was run and the headline
numbers, so the Result folder is self-explanatory without re-reading code.
"""
import os

import pandas as pd

RESULT_DIR = os.environ.get('KD_RESULT_DIR', os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'results'))


def main():
    summary_path = os.path.join(RESULT_DIR, 'eer_by_mechanism_delta.csv')
    summary = pd.read_csv(summary_path)

    primary_k = 5  # must match RunConfig.primary_k in run_experiments.py
    primary = summary[(summary['k_enrollment'] == primary_k) & (summary['clipped'] == 'clipped')]

    lines = []
    lines.append('# Experiment Results\n')
    lines.append('Generated by `experiments/run_experiments.py` (see that file\'s docstring and the paper '
                  'draft, Section 3, for the full protocol). Every table/figure referenced below lives in '
                  'this folder.\n')

    lines.append('## Files\n')
    lines.append('- `password_metadata.csv` - the 40 recovered passwords with length + substitution category\n')
    lines.append('- `trials_test.parquet` / `trials_val.parquet` - every individual verification trial (score, '
                  'label, covariates) for the test/validation participants of each fold\n')
    lines.append('- `eer_by_mechanism_delta.csv` - EER/FNMR summary per (mechanism, clipped, k, delta)\n')
    lines.append('- `mixed_model_input.parquet` - trial-level table with the calibrated `is_error` outcome used '
                  'by the mixed-effects model\n')
    lines.append('- `stats_model/mixed_model_summary.txt` - full mixed-effects model output + LR test\n')
    lines.append('- `stats_model/robustness_check_notes.md` - the seed-robustness check that caught (and fixed) an '
                  'unstable earlier version of this model; read this before citing the LR test below\n')
    lines.append('- `figures/aging_curve.png` - EER vs. temporal gap per mechanism (Section 3.4 aging curve)\n')
    lines.append('- `figures/det_curve_*.png` - DET curves per clipping condition (Section 3.6)\n')
    lines.append('- `run_log.txt` - console log of the run (timings, trial counts)\n')

    lines.append('\n## Overall EER by mechanism (primary k=%d, clipped, pooled across folds and delta)\n' % primary_k)
    overall = primary.groupby('mechanism').apply(
        lambda g: pd.Series({
            'n_trials': g['n_trials'].sum(),
            'eer_pooled_range': f"{g['eer_pooled'].min():.3%} - {g['eer_pooled'].max():.3%}",
            'eer_at_delta_0': g.loc[g['delta'] == 0, 'eer_pooled'].values[0] if (g['delta'] == 0).any() else float('nan'),
            'eer_at_delta_7': g.loc[g['delta'] == 7, 'eer_pooled'].values[0] if (g['delta'] == 7).any() else float('nan'),
        }), include_groups=False
    )
    lines.append(overall.to_markdown())

    lr_path = os.path.join(RESULT_DIR, 'stats_model', 'mixed_model_summary.txt')
    if os.path.exists(lr_path):
        with open(lr_path, encoding='utf-8') as f:
            content = f.read()
        lr_line = [l for l in content.splitlines() if l.startswith('LR stat')]
        lines.append('\n## Mixed-effects model: does aging rate depend on matching mechanism?\n')
        if lr_line:
            lines.append(f'Likelihood-ratio test for the Delta x Mechanism interaction: {lr_line[0]}\n')
        lines.append('See `stats_model/mixed_model_summary.txt` for full fixed/random-effect estimates.\n')

    out_path = os.path.join(RESULT_DIR, 'README.md')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {out_path}')


if __name__ == '__main__':
    main()
